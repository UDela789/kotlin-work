fun main() {
    // unsigned INT
    val myAge = 29u
    println(myAge::class)
    // signed long
    val universeAge = 13_800_000_000L
    println(universeAge::class)
    // char
    val status = 'M'
    println(status::class)
    // string
    val name = "Sarah"
    println(name::class)
    // float
    val height = 1.78f
    println(height::class)
    // double
    val root2 = Math.sqrt(2.0)
    println(root2::class)
}
